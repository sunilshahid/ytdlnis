package com.deniscerri.ytdl.playback.resolve

import android.content.Context
import android.net.Uri
import android.provider.MediaStore
import com.deniscerri.ytdl.playback.model.PlaybackExtrasCodec
import com.deniscerri.ytdl.playback.model.PlaybackSubtitle
import java.io.File
import java.util.Locale

object SubtitleSidecarFinder {
    val SUPPORTED_EXTENSIONS = setOf("srt", "vtt", "ass", "ssa", "ttml")

    fun extractSidecarMatch(videoBaseName: String, candidateFileName: String): Pair<String?, String>? {
        if (videoBaseName.isBlank()) return null
        val dot = candidateFileName.lastIndexOf('.')
        if (dot <= 0 || dot >= candidateFileName.lastIndex) return null
        val ext = candidateFileName.substring(dot + 1).lowercase(Locale.ROOT)
        if (ext !in SUPPORTED_EXTENSIONS) return null

        val stem = candidateFileName.substring(0, dot)
        if (stem.equals(videoBaseName, ignoreCase = true)) {
            return null to ext.uppercase(Locale.ROOT)
        }
        val prefix = "$videoBaseName."
        if (stem.startsWith(prefix, ignoreCase = true)) {
            val langTag = stem.substring(prefix.length).trim()
            if (langTag.isNotEmpty() && langTag.length <= 16) {
                val langDisplay = runCatching {
                    Locale.forLanguageTag(langTag.replace('_', '-')).displayName
                }.getOrNull()?.takeIf { it.isNotBlank() && !it.equals(langTag, ignoreCase = true) }
                val label = if (langDisplay != null) {
                    "$langDisplay (${ext.uppercase(Locale.ROOT)})"
                } else {
                    "${langTag.uppercase(Locale.ROOT)} (${ext.uppercase(Locale.ROOT)})"
                }
                return langTag to label
            }
            return null to ext.uppercase(Locale.ROOT)
        }
        return null
    }

    fun findForMedia(context: Context, localUri: String?): List<PlaybackSubtitle> {
        val mediaFile = resolveLocalFile(context, localUri) ?: return emptyList()
        val parentDir = mediaFile.parentFile?.takeIf { it.isDirectory && it.canRead() } ?: return emptyList()
        val baseName = mediaFile.nameWithoutExtension.takeIf { it.isNotBlank() } ?: return emptyList()

        val searchDirs = listOfNotNull(
            parentDir,
            File(parentDir, "Subtitles").takeIf { it.isDirectory && it.canRead() },
            File(parentDir, "subtitles").takeIf { it.isDirectory && it.canRead() }
        ).distinctBy { it.absolutePath }

        val deviceLang = Locale.getDefault().language.lowercase(Locale.ROOT)
        val found = LinkedHashMap<String, PlaybackSubtitle>()

        searchDirs.forEach { dir ->
            val files = dir.listFiles() ?: return@forEach
            files.forEach { candidate ->
                if (!candidate.isFile || !candidate.canRead()) return@forEach
                val match = extractSidecarMatch(baseName, candidate.name) ?: return@forEach
                val (lang, label) = match
                val uri = Uri.fromFile(candidate).toString()
                if (!found.containsKey(uri)) {
                    found[uri] = PlaybackSubtitle(
                        uri = uri,
                        mimeType = PlaybackExtrasCodec.inferSubtitleMimeType(candidate.name),
                        language = lang,
                        label = label,
                        isAutoGenerated = false,
                        isLocal = true
                    )
                }
            }
        }

        return found.values.sortedWith(
            compareByDescending<PlaybackSubtitle> { it.language == null }
                .thenByDescending { it.language?.lowercase(Locale.ROOT) == deviceLang }
                .thenBy { it.label }
        )
    }

    @Suppress("DEPRECATION")
    private fun resolveLocalFile(context: Context, localUri: String?): File? {
        val raw = localUri?.trim()?.takeIf { it.isNotEmpty() } ?: return null
        return when {
            raw.startsWith("file://") -> {
                val path = runCatching { Uri.parse(raw).path }.getOrNull() ?: return null
                File(path).takeIf { it.exists() }
            }
            raw.startsWith("/") -> File(raw).takeIf { it.exists() }
            raw.startsWith("content://") -> {
                val parsed = runCatching { Uri.parse(raw) }.getOrNull() ?: return null
                runCatching {
                    context.contentResolver.query(
                        parsed,
                        arrayOf(MediaStore.MediaColumns.DATA),
                        null,
                        null,
                        null
                    )?.use { cursor ->
                        if (cursor.moveToFirst()) {
                            val idx = cursor.getColumnIndex(MediaStore.MediaColumns.DATA)
                            if (idx >= 0) {
                                val path = cursor.getString(idx)
                                if (!path.isNullOrBlank()) return@runCatching File(path).takeIf { it.exists() }
                            }
                        }
                        null
                    }
                }.getOrNull()
            }
            else -> null
        }
    }
}
