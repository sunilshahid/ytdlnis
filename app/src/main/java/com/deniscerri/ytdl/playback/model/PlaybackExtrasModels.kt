package com.deniscerri.ytdl.playback.model

import androidx.media3.common.MimeTypes
import com.deniscerri.ytdl.database.models.ChapterItem
import org.json.JSONArray
import org.json.JSONObject
import java.util.Locale
import kotlin.math.roundToLong

data class PlaybackSubtitle(
    val uri: String,
    val mimeType: String,
    val language: String? = null,
    val label: String,
    val isAutoGenerated: Boolean = false,
    val isLocal: Boolean = false
)

data class PlaybackChapter(
    val startMs: Long,
    val endMs: Long,
    val title: String
)

object PlaybackExtrasCodec {

    fun subtitlesToJson(list: List<PlaybackSubtitle>): String {
        val arr = JSONArray()
        list.forEach { sub ->
            arr.put(
                JSONObject().apply {
                    put("uri", sub.uri)
                    put("mimeType", sub.mimeType)
                    sub.language?.let { put("language", it) }
                    put("label", sub.label)
                    put("isAutoGenerated", sub.isAutoGenerated)
                    put("isLocal", sub.isLocal)
                }
            )
        }
        return arr.toString()
    }

    fun subtitlesFromJson(raw: String?): List<PlaybackSubtitle> {
        if (raw.isNullOrBlank()) return emptyList()
        return runCatching {
            val arr = JSONArray(raw)
            buildList(arr.length()) {
                for (i in 0 until arr.length()) {
                    val obj = arr.optJSONObject(i) ?: continue
                    val uri = obj.optString("uri").takeIf { it.isNotBlank() } ?: continue
                    val mimeType = obj.optString("mimeType").ifBlank { inferSubtitleMimeType(uri) }
                    val language = obj.optString("language").takeIf { it.isNotBlank() }
                    val label = obj.optString("label").ifBlank { language ?: "Subtitles" }
                    add(
                        PlaybackSubtitle(
                            uri = uri,
                            mimeType = mimeType,
                            language = language,
                            label = label,
                            isAutoGenerated = obj.optBoolean("isAutoGenerated", false),
                            isLocal = obj.optBoolean("isLocal", false)
                        )
                    )
                }
            }
        }.getOrDefault(emptyList())
    }

    fun chaptersToJson(list: List<PlaybackChapter>): String {
        val arr = JSONArray()
        list.forEach { chapter ->
            arr.put(
                JSONObject().apply {
                    put("startMs", chapter.startMs)
                    put("endMs", chapter.endMs)
                    put("title", chapter.title)
                }
            )
        }
        return arr.toString()
    }

    fun chaptersFromJson(raw: String?): List<PlaybackChapter> {
        if (raw.isNullOrBlank()) return emptyList()
        return runCatching {
            val arr = JSONArray(raw)
            buildList(arr.length()) {
                for (i in 0 until arr.length()) {
                    val obj = arr.optJSONObject(i) ?: continue
                    val startMs = obj.optLong("startMs", -1L).coerceAtLeast(0L)
                    val endMs = obj.optLong("endMs", startMs).coerceAtLeast(startMs)
                    val title = obj.optString("title").ifBlank { "Chapter ${i + 1}" }
                    add(PlaybackChapter(startMs = startMs, endMs = endMs, title = title))
                }
            }
        }.getOrDefault(emptyList())
    }

    fun parseYtDlpChapters(arr: JSONArray?): List<PlaybackChapter> {
        arr ?: return emptyList()
        val parsed = ArrayList<PlaybackChapter>(arr.length())
        for (i in 0 until arr.length()) {
            val obj = arr.optJSONObject(i) ?: continue
            val startSec = obj.optDouble("start_time", Double.NaN)
            if (startSec.isNaN() || startSec < 0.0) continue
            val endSec = obj.optDouble("end_time", startSec).takeUnless { it.isNaN() || it < startSec } ?: startSec
            val startMs = (startSec * 1000.0).roundToLong()
            val endMs = (endSec * 1000.0).roundToLong().coerceAtLeast(startMs)
            val title = obj.optString("title").ifBlank { "Chapter ${i + 1}" }
            parsed.add(PlaybackChapter(startMs = startMs, endMs = endMs, title = title))
        }
        return parsed.sortedBy { it.startMs }
    }

    fun chaptersFromChapterItems(items: List<ChapterItem>): List<PlaybackChapter> {
        return items.mapIndexed { idx, item ->
            val startMs = (item.start_time.coerceAtLeast(0L)) * 1000L
            val endMs = (item.end_time.coerceAtLeast(item.start_time)) * 1000L
            PlaybackChapter(
                startMs = startMs,
                endMs = endMs,
                title = item.title.ifBlank { "Chapter ${idx + 1}" }
            )
        }.sortedBy { it.startMs }
    }

    fun inferSubtitleMimeType(extOrUri: String): String {
        val clean = extOrUri.substringBefore('?').substringBefore('#').lowercase(Locale.ROOT)
        return when {
            clean == "vtt" || clean.endsWith(".vtt") -> MimeTypes.TEXT_VTT
            clean == "srt" || clean.endsWith(".srt") -> MimeTypes.APPLICATION_SUBRIP
            clean == "ass" || clean == "ssa" || clean.endsWith(".ass") || clean.endsWith(".ssa") -> MimeTypes.TEXT_SSA
            clean == "ttml" || clean == "xml" || clean.endsWith(".ttml") -> MimeTypes.APPLICATION_TTML
            else -> MimeTypes.TEXT_VTT
        }
    }

    fun findActiveChapterIndex(chapters: List<PlaybackChapter>, positionMs: Long): Int {
        if (chapters.isEmpty()) return -1
        val pos = positionMs.coerceAtLeast(0L)
        for (i in chapters.indices.reversed()) {
            if (pos >= chapters[i].startMs) return i
        }
        return 0
    }

    fun formatTimestampMs(ms: Long): String {
        val totalSeconds = (ms.coerceAtLeast(0L) / 1000L)
        val hours = totalSeconds / 3600L
        val minutes = (totalSeconds % 3600L) / 60L
        val seconds = totalSeconds % 60L
        return if (hours > 0L) {
            String.format(Locale.ROOT, "%d:%02d:%02d", hours, minutes, seconds)
        } else {
            String.format(Locale.ROOT, "%02d:%02d", minutes, seconds)
        }
    }
}
